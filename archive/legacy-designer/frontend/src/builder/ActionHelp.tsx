import { useTranslation } from '../i18n'
import { contextExpression } from './model'

export function ActionHelp({ switchId }: { switchId?: string }) {
  const { t } = useTranslation()
  const toggle = contextExpression(switchId ?? 'switchId')
  return <section id="builder-action-help" className="action-help" aria-label={t('Справка по API действий')}>
    <h4>{t('Как связать действия Python')}</h4>
    <p>{t('Задайте кнопке команду refresh и создайте действие Python с таким запуском. Добавьте два действия с командами enabled и disabled.')}</p>
    <pre><code>{`def run(context):
    if ${toggle}:
        emit("enabled")
    else:
        emit("disabled")`}</code></pre>
    <p>{t(switchId ? 'В примере подставлен ID переключателя из шаблона.' : 'Замените switchId на ID своего переключателя.')}
      {' '}{t('Двойной щелчок по элементу предпросмотра копирует выражение для чтения его значения.')}</p>
    <p>{t('Функция emit("имя") запускает действия с такой командой в этой карточке. Команды выполняются по очереди после успешной обработки результата. Для развилки список получателей можно оставить пустым. Поле с совпадающей командой сброса очищается через полсекунды.')}</p>
    <p>{t('Ошибка останавливает цепочку. Повторный запуск действия в той же ветви считается циклом. Предел цепочки — 64 запуска.')}</p>
    <h4>{t('Значения и результат')}</h4>
    <p>{t('Значение доступно через context["values"][id]. Переключатель даёт True или False, слайдер — число, поле ввода — строку, кнопка — подпись. Текст и индикатор дают текущее значение. Ключи instance_id, template_id и action_id содержат ID экземпляра, шаблона и действия.')}</p>
    <pre><code>{`return {"text": "${t('Готово')}", "color": "green"}`}</code></pre>
    <p>{t('Верните значение через return или верните словарь и укажите ключ в поле результата. В примере назначьте text тексту и color индикатору. Следующий шаг видит обновлённые значения. Вывод print() появится в карточке. Лимит Python — 4 секунды на запуск.')}</p>
    <h4>HTTP GET</h4>
    <p>{t('Укажите URL источника JSON. В поле JSON можно выбрать путь, например cpu.temperature. Пустой путь возвращает весь ответ.')}</p>
    <h4>{t('Проверка доступности')}</h4>
    <p>{t('Введите IP или имя хоста. Пустой порт включает ICMP, указанный порт — проверку TCP. Назначьте получателям поля text и color. Поле available содержит логическое значение.')}</p>
  </section>
}
