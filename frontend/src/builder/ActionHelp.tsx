import { contextExpression } from './model'

export function ActionHelp({ switchId }: { switchId?: string }) {
  const toggle = contextExpression(switchId ?? 'switchId')
  return <section id="builder-action-help" className="action-help" aria-label="Справка по API действий">
    <h4>Как связать действия Python</h4>
    <p>Задайте кнопке команду <code>refresh</code>. Создайте действие Python с запуском по этой команде.
      Добавьте ещё два действия с командами запуска <code>enabled</code> и <code>disabled</code>.</p>
    <pre><code>{`def run(context):
    if ${toggle}:
        emit("enabled")
    else:
        emit("disabled")`}</code></pre>
    <p>{switchId ? 'В примере подставлен ID переключателя из шаблона.' : 'Замените switchId на ID своего переключателя.'}
      {' '}Двойной щелчок по элементу предпросмотра копирует выражение для чтения его значения.</p>
    <p><code>emit("имя")</code> запускает действия с точно такой командой в этой карточке.
      Команды выполняются по очереди после успешного возврата и обработки результата. Для развилки по команде список получателей результата можно оставить пустым.
      Поле с совпадающей командой сброса очищается через полсекунды.</p>
    <p>Ошибка останавливает цепочку. Возврат к действию, которое уже выполняется в этой ветви, считается циклом. Предел цепочки — 64 запуска.</p>
    <h4>Значения и результат</h4>
    <p><code>context["values"][id]</code> содержит значение по ID элемента. Для переключателя это True или False,
      для слайдера — число, для поля ввода — строка, для кнопки — подпись. Текст и индикатор содержат
      текущее отображаемое значение. ID экземпляра, шаблона и действия доступны по ключам <code>instance_id</code>, <code>template_id</code> и <code>action_id</code>.</p>
    <p>Верните значение через <code>return</code> или верните словарь и укажите ключ в «Поле результата» у каждого получателя.
      Например, для <code>{'return {"text": "Готово", "color": "green"}'}</code> назначьте тексту поле <code>text</code>, индикатору — <code>color</code>.
      Следующий шаг видит обновлённые значения. Вывод <code>print()</code> появится в карточке. Лимит Python — 4 секунды на запуск.</p>
    <h4>HTTP GET</h4>
    <p>Укажите URL источника JSON. Сервер получит ответ. В «Поле JSON» можно выбрать значение по пути,
      например <code>cpu.temperature</code>. Пустой путь возвращает весь ответ.</p>
    <h4>Проверка доступности</h4>
    <p>Введите IP или имя хоста. Пустой порт включает ICMP, указанный порт — проверку TCP.
      Назначьте получателям поля <code>text</code> и <code>color</code>. Поле <code>available</code> содержит логическое значение.</p>
  </section>
}
